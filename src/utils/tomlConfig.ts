import type {
  EndpointFileAttachment,
  ExecutionConfig,
  ProviderEndpoint,
  SupabaseConfig,
  SystemPromptConfig,
  TargetModel,
  ThemeId,
} from '../types/benchmark';

function tomlString(val: string): string {
  return JSON.stringify(val ?? '');
}

function defaultEnvVarForProvider(kind: ProviderEndpoint['kind']): string {
  switch (kind) {
    case 'openai':
      return 'OPENAI_API_KEY';
    case 'groq':
      return 'GROQ_API_KEY';
    case 'litellm':
      return 'LITELLM_API_KEY';
    case 'vllm':
      return 'VLLM_API_KEY';
    case 'gemini-builtin':
      return 'GEMINI_API_KEY';
    default:
      return '';
  }
}

export interface TomlExportInput {
  executionConfig: ExecutionConfig;
  systemPrompt: SystemPromptConfig;
  theme: ThemeId;
  supabaseConfig: SupabaseConfig;
  providers: ProviderEndpoint[];
  targets: TargetModel[];
  endpointFiles?: EndpointFileAttachment[];
  includeInlineSecrets?: boolean;
}

export function generateBenchforgeToml(input: TomlExportInput): string {
  const {
    executionConfig,
    systemPrompt,
    theme,
    supabaseConfig,
    providers,
    targets,
    endpointFiles = [],
    includeInlineSecrets = false,
  } = input;

  const lines: string[] = [
    '# Generated by BenchForge Workbench for benchforge-tui',
    '# Save as ./benchforge.toml or ~/.config/benchforge/config.toml',
    '',
    '[execution]',
    `mode = ${tomlString(executionConfig.mode)}`,
    `concurrency = ${Math.min(Math.max(executionConfig.concurrency, 1), 100)}`,
    `timeout_sec = ${Math.min(Math.max(executionConfig.timeoutSec, 5), 600)}`,
    `stream = ${executionConfig.stream}`,
    `temperature = ${executionConfig.temperature}`,
    `max_tokens = ${executionConfig.maxTokens}`,
    `top_p = ${executionConfig.topP}`,
    `endpoint_type = ${tomlString(executionConfig.endpointType ?? 'chat-completions')}`,
  ];

  if (executionConfig.customEndpoint?.trim()) {
    lines.push(`custom_endpoint = ${tomlString(executionConfig.customEndpoint.trim())}`);
  }
  if (executionConfig.ttsVoice?.trim()) {
    lines.push(`tts_voice = ${tomlString(executionConfig.ttsVoice.trim())}`);
  }
  if (typeof executionConfig.seed === 'number') {
    lines.push(`seed = ${executionConfig.seed}`);
  }

  lines.push(
    '',
    '[system_prompt]',
    `enabled = ${systemPrompt.enabled}`,
    ...(systemPrompt.personaId ? [`persona = ${tomlString(systemPrompt.personaId)}`] : []),
    `target_mode = ${tomlString(systemPrompt.targetMode)}`,
    `target_models = [${systemPrompt.targetModelIds.map(tomlString).join(', ')}]`,
    `content = ${tomlString(systemPrompt.content)}`,
    '',
    '[ui]',
    `theme = ${tomlString(theme)}`,
    'history_limit = 50',
    '',
    '[supabase]',
    `url = ${tomlString(supabaseConfig.url)}`,
    'anon_key_env = "SUPABASE_ANON_KEY"',
    ...(includeInlineSecrets && supabaseConfig.anonKey
      ? [`anon_key = ${tomlString(supabaseConfig.anonKey)}`]
      : []),
    `table_name = ${tomlString(supabaseConfig.tableName || 'benchmark_runs')}`,
    `auto_sync = ${supabaseConfig.autoSync}`
  );

  for (const p of providers) {
    const resolvedBaseUrl =
      p.kind === 'gemini-builtin'
        ? 'https://generativelanguage.googleapis.com/v1beta/openai'
        : p.baseUrl;

    const envVar = defaultEnvVarForProvider(p.kind);
    lines.push(
      '',
      '[[providers]]',
      `id = ${tomlString(p.id)}`,
      `name = ${tomlString(p.name)}`,
      `kind = ${tomlString(p.kind)}`,
      `base_url = ${tomlString(resolvedBaseUrl)}`,
      `api_key_env = ${tomlString(envVar)}`,
      ...(includeInlineSecrets && p.apiKey ? [`api_key = ${tomlString(p.apiKey)}`] : []),
      `models = [${p.models.map(tomlString).join(', ')}]`
    );

    const headerEntries = Object.entries(p.customHeaders);
    if (headerEntries.length > 0) {
      lines.push('[providers.custom_headers]');
      for (const [k, v] of headerEntries) {
        lines.push(`${tomlString(k)} = ${tomlString(includeInlineSecrets ? v : '')}`);
      }
    }
  }

  for (const t of targets) {
    lines.push(
      '',
      '[[targets]]',
      `id = ${tomlString(t.id)}`,
      `provider_id = ${tomlString(t.providerId)}`,
      `model = ${tomlString(t.modelName)}`,
      `enabled = ${t.enabled}`
    );
    if (t.systemPromptOverride?.trim()) {
      lines.push(`system_prompt_override = ${tomlString(t.systemPromptOverride.trim())}`);
    }
  }

  for (const f of endpointFiles) {
    lines.push(
      '',
      '[[endpoint_files]]',
      `id = ${tomlString(f.id)}`,
      `path = ${tomlString(f.name)}`,
      `mime_type = ${tomlString(f.mimeType)}`,
      `endpoint_type = ${tomlString(f.endpointScope)}`,
      `field_name = ${tomlString(f.fieldName || 'file')}`,
      `enabled = ${f.enabled}`
    );
  }

  lines.push('');
  return lines.join('\n');
}
